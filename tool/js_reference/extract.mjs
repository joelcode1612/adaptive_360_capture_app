// ── 1. adaptive_360_realistic_test.html — the /*ENGINE*/ block ──────────────
{
  const src = 'adaptive_360_realistic_test.html';
  const a = findLine(src, /^\/\*ENGINE\*\/$/, 1);
  const b = findLine(src, /^\/\*ENDENGINE\*\/$/, 1);
  const text = slice(src, a + 1, b - 1);
  const exportNames = ENGINE_EXPORTS;
  jobs.push({
    file: 'engine_realistic_test.js',
    text:
      header({
        source: src,
        range: `${a + 1}..${b - 1}`,
        bytes: Buffer.byteLength(text),
        sha: sha256(text),
      }) +
      '// This whole slice is the engine. It touches no browser API, so nothing\n' +
      '// had to be omitted. `runTests()` is included: it is the prototype\'s own\n' +
      '// 32-check self-test and its results are part of the parity surface.\n\n' +
      '/* SOURCE BEGIN */\n' +
      text +
      '\n/* SOURCE END */\n' +
      optionalGuard() +
      footer(exportNames),
  });
}

