// Generates the four JS reference modules from the HTML prototypes.
//
//   node tool/js_reference/extract.mjs ["<Downloads dir>"]
//
// Each module is a BYTE-VERBATIM slice of the inline `<script>` of one HTML
// file, plus a generated export footer. Nothing in the slice is edited: no
// renames, no formatting, no bug fixes. If a slice's SHA-256 in the header
// matches the HTML, the maths in this directory is the maths the prototype ran.
//
// The four sources are read-only inputs. This script never writes outside
// tool/js_reference/.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const downloads =
  process.argv[2] || 'C:/Users/Lenovo/Downloads';

const sha256 = (s) => crypto.createHash('sha256').update(s, 'utf8').digest('hex');

const linesOf = (file) => fs.readFileSync(path.join(downloads, file), 'utf8').split(/\r?\n/);

/**
 * Verbatim line slice, 1-based inclusive.
 */
function slice(file, from, to) {
  const L = linesOf(file);
  if (!(from >= 1 && to <= L.length && from <= to)) {
    throw new Error(`bad range ${from}..${to} for ${file} (${L.length} lines)`);
  }
  return L.slice(from - 1, to).join('\n');
}

/**
 * Finds the unique line index (1-based) matching `re`, dying loudly if the
 * prototype was edited under us rather than silently slicing the wrong thing.
 */
function findLine(file, re, expected = 1) {
  const L = linesOf(file);
  const hits = L.map((l, i) => (re.test(l) ? i + 1 : 0)).filter(Boolean);
  if (hits.length !== expected) {
    throw new Error(
      `${file}: pattern ${re} matched ${hits.length} lines (${hits.join(',')}), expected ${expected}`,
    );
  }
  return hits[0];
}

const header = (o) =>
  `// ──────────────────────────────────────────────────────────────────────────
// GENERATED BY \`node tool/js_reference/extract.mjs\` — do not hand-edit.
//
// Source file : ${o.source}
// Source lines: ${o.range} (1-based, inclusive, of the file as it stands)
// Slice bytes : ${o.bytes}
// Slice SHA256: ${o.sha}
//
// The block between the SOURCE BEGIN / SOURCE END markers below is a
// byte-for-byte copy of that range. Only the export footer is generated.
// Bugs found in the source are deliberately NOT fixed here — see
// docs/JS_PARITY_DISCREPANCIES.md.
// ──────────────────────────────────────────────────────────────────────────

`;

const footer = (names) =>
  `\n
// ── generated export footer (not part of the source slice) ────────────────
// \`S\`, \`plan\`, \`steps\` and friends are re-bound by the page's own code, so
// they are exported through getters: a value export would freeze the object
// that existed at load time and silently diverge from the running prototype.
module.exports = {
${names
  .map(
    (n) =>
      `  get ${n}() {
    try {
      return ${n};
    } catch (e) {
      return undefined; /* not declared in this source */
    }
  },`,
  )
  .join('\n')}
};
`;

/**
 * No guard is emitted for names a slice does not bind. The export getters above
 * are wrapped in try/catch, which is both safer and honest: a `var` pre-declaration
 * would collide ("already declared") with any name bound inside a multi-declarator
 * `const` statement that spans several lines, which is exactly how these
 * prototypes are written. `run_reference.mjs` asserts on each export it uses, so
 * an undefined one fails loudly rather than silently.
 */
const optionalGuard = () => '';

const jobs = [];

/**
 * Export lists are written out rather than derived, because these prototypes
 * declare most of their helpers inside multi-declarator `const` statements that
 * span several lines (`const D2R=...,R2D=...,clamp=...,wrap=...`), which a
 * line-start regex cannot see. A hand-written list is also a statement about
 * what the parity harness believes the reference API *is*.
 */
